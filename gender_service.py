def normalize_name(value: str) -> str:
    value = (value or "").strip().lower().replace("ё", "е")
    value = re.sub(r"[^a-zа-я\- ]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()

def detect_gender(name: str) -> str:
    """Возвращает 'female', 'male' или 'unknown'."""
    normalized = normalize_name(name)
    if not normalized:
        return "unknown"
    parts = normalized.split()
    first = parts[0]

    if first in FEMALE_NAMES and first not in {"саша","женя","валя"}:
        return "female"
    if first in MALE_NAMES and first not in {"саша","женя","валя"}:
        return "male"

    # Если введено имя + отчество/ФИО, используем форму отчества как дополнительный сигнал.
    for token in parts[1:]:
        if re.search(r"(овна|евна|ична|инична|овская|евская)$", token):
            return "female"
        if re.search(r"(ович|евич|ич)$", token):
            return "male"

    # Типовые окончания имён. Не используем их для неоднозначных коротких форм.
    if first in {"саша","женя","валя"}:
        return "unknown"
    if first.endswith(("а","я","ия")) and len(first) > 3:
        return "female"
    if first.endswith(("й","н","р","л","м","в","д","г","с","т","к","п")) and len(first) > 3:
        return "male"

    return "unknown"

def gender_title(gender: str) -> str:
    return {"female":"женский вариант", "male":"мужской вариант"}.get(gender, "универсальный вариант")
